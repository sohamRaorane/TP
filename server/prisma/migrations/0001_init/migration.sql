CREATE TABLE IF NOT EXISTS "Drawing" (
  "id" TEXT NOT NULL PRIMARY KEY,
  "name" TEXT NOT NULL DEFAULT 'Untitled drawing',
  "data" JSONB NOT NULL,
  "thumbnail" TEXT,
  "elementCount" INTEGER NOT NULL DEFAULT 0,
  "revision" INTEGER NOT NULL DEFAULT 1,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMP(3) NOT NULL
);
CREATE TABLE IF NOT EXISTS "DrawingVersion" (
  "id" TEXT NOT NULL PRIMARY KEY,
  "drawingId" TEXT NOT NULL REFERENCES "Drawing"("id") ON DELETE CASCADE ON UPDATE CASCADE,
  "data" JSONB NOT NULL,
  "elementCount" INTEGER NOT NULL DEFAULT 0,
  "label" TEXT,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS "DrawingVersion_drawingId_createdAt_idx" ON "DrawingVersion"("drawingId", "createdAt");
CREATE TABLE IF NOT EXISTS "ShareLink" (
  "id" TEXT NOT NULL PRIMARY KEY,
  "drawingId" TEXT NOT NULL REFERENCES "Drawing"("id") ON DELETE CASCADE ON UPDATE CASCADE,
  "mode" TEXT NOT NULL,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
